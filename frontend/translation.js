const DEFAULT_LANG = "en";
const SUPPORTED_LANGS = Object.keys(TRANSLATIONS);

function getTranslation(lang, key) {
  if (!lang || !SUPPORTED_LANGS.includes(lang)) {
    lang = DEFAULT_LANG;
  }
  const segments = key.split(".");
  let current = TRANSLATIONS[lang];

  for (const segment of segments) {
    if (current && Object.prototype.hasOwnProperty.call(current, segment)) {
      current = current[segment];
    } else {
      current = undefined;
      break;
    }
  }

  if (current !== undefined) {
    return current;
  }

  return key.split('.').slice(-1)[0].replace(/([A-Z])/g, ' $1').trim();
}

function translatePage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) {
    lang = DEFAULT_LANG;
  }

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.classList.toggle("rtl", lang === "ar");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const value = getTranslation(lang, key);
    if (element.tagName === "INPUT" || element.tagName === "TEXTAREA" || element.tagName === "SELECT") {
      if (element.placeholder !== undefined) {
        element.placeholder = value;
      }
      if (element.tagName === "INPUT" && element.type === "submit") {
        element.value = value;
      }
    } else {
      element.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    element.setAttribute("placeholder", getTranslation(lang, key));
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.dataset.i18nHtml;
    element.innerHTML = getTranslation(lang, key);
  });

  const titleElement = document.querySelector("title[data-i18n-title]");
  if (titleElement) {
    document.title = getTranslation(lang, titleElement.dataset.i18nTitle);
  }

  const languageSelect = document.getElementById("language-select");
  if (languageSelect) {
    languageSelect.value = lang;
  }
}

function initLanguageSelector() {
  const select = document.getElementById("language-select");
  if (!select) {
    return;
  }

  select.innerHTML = SUPPORTED_LANGS.map((lang) => {
    const label = TRANSLATIONS[lang].common.languageName || lang.toUpperCase();
    return `<option value="${lang}">${label}</option>`;
  }).join("");

  const activeLang = localStorage.getItem("siteLang") || DEFAULT_LANG;
  select.value = SUPPORTED_LANGS.includes(activeLang) ? activeLang : DEFAULT_LANG;

  select.addEventListener("change", (event) => {
    const newLang = event.target.value;
    localStorage.setItem("siteLang", newLang);
    translatePage(newLang);
  });
}

function initTranslations() {
  initLanguageSelector();
  const savedLanguage = localStorage.getItem("siteLang") || DEFAULT_LANG;
  translatePage(savedLanguage);
}

document.addEventListener("DOMContentLoaded", initTranslations);
